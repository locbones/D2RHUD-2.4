"""Generate relocation and unwind metadata, not executable code.
Usage: python tests/generate-states-512-native.py D2R.exe [output-header]
Dependencies: pefile, capstone. The SHA-256 gate intentionally rejects other builds.
"""
from pathlib import Path
import hashlib
import struct
import sys
import capstone
import pefile

source = Path(sys.argv[1])
expected = "2C2DDB60A40EDE3AAFF51AFB64E932621A03E32487687B6C64D88205FA652360"
if hashlib.sha256(source.read_bytes()).hexdigest().upper() != expected:
    raise SystemExit("Unsupported executable: native code must be audited first")
pe = pefile.PE(str(source))
data = pe.get_memory_mapped_image()
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)

# Exact copies of the three native single-state receivers; widen only their
# local input view. Wire packets keep their native framing and byte lengths.
handlers=[(0xdd7d0,0xdd82f,0),(0xdd830,0xdda2d,0x100),(0xdda30,0xddb66,0x400)]
md.detail=True
fixups=[];unwind={};runtime=[]
def uw(r):
 if r in unwind:return
 first=data[r:r+4];flags=first[0]>>3;n=4+((first[2]+1)&~1)*2
 assert flags in [0,4],(hex(r),flags)
 chunk=bytearray(data[r:r+n+(12 if flags&4 else 0)]);unwind[r]=chunk
 if flags&4:
  a,b,u=struct.unpack_from('<III',chunk,n);uw(u)
for a,b,dest in handlers:
 for ins in md.disasm(data[a:b],a):
  if ins.disp_size==4 and any(op.type==capstone.CS_OP_MEM and op.mem.base==capstone.x86.X86_REG_RIP for op in ins.operands):fixups.append((dest+ins.address-a+ins.disp_offset,ins.address+ins.size+ins.disp))
  if ins.group(capstone.CS_GRP_CALL) or ins.group(capstone.CS_GRP_JUMP):
   if ins.operands and ins.operands[0].type==capstone.CS_OP_IMM:
    target=ins.operands[0].imm
    if not a<=target<b:
     assert ins.imm_size==4,(hex(ins.address),ins.op_str);fixups.append((dest+ins.address-a+ins.imm_offset,target))
 for e in pe.DIRECTORY_ENTRY_EXCEPTION:
  x=e.struct
  if a<=x.BeginAddress<b:
   assert x.EndAddress<=b,(hex(x.BeginAddress),hex(x.EndAddress));runtime.append((dest+x.BeginAddress-a,dest+x.EndAddress-a,x.UnwindData));uw(x.UnwindData)
 offsets={};nextoff=0x800
for r,chunk in unwind.items():offsets[r]=nextoff;nextoff=(nextoff+len(chunk)+3)&~3
for r,chunk in unwind.items():
 if chunk[0]>>3&4:
  n=4+((chunk[2]+1)&~1)*2;x,y,u=struct.unpack_from('<III',chunk,n)
  matches=[(a,b,d) for a,b,d in handlers if a<=x<y<=b];assert len(matches)==1,(hex(x),hex(y))
  a,b,d=matches[0];struct.pack_into('<III',chunk,n,d+x-a,d+y-a,offsets[u])
runtime=[(a,b,offsets[u]) for a,b,u in runtime]
# disp32 relocation locations refer to an instruction's end because each is
# the last four bytes of its instruction in these routines.
for a,b,dest in handlers:
 for ins in md.disasm(data[a:b],a):
  if ins.disp_size==4 and any(op.type==capstone.CS_OP_MEM and op.mem.base==capstone.x86.X86_REG_RIP for op in ins.operands):assert ins.disp_offset+4==ins.size
  if (ins.group(capstone.CS_GRP_CALL) or ins.group(capstone.CS_GRP_JUMP)) and ins.operands and ins.operands[0].type==capstone.CS_OP_IMM and not a<=ins.operands[0].imm<b:assert ins.imm_offset+4==ins.size
out=['// Generated by tests/generate-states-512-native.py from the audited D2R.exe.', '// Only relocation/unwind metadata is stored; runtime code comes from the game.', '#pragma once','#include <array>','#include <cstdint>','namespace States512::NativeData {','struct Copy {uint32_t source, size, destination;};','inline constexpr std::array<Copy,3> Copies{{']
for a,b,d in handlers:out.append('    {0x%x,0x%x,0x%x},'%(a,b-a,d))
out+=['}};','struct Fixup {uint32_t offset,target;};','inline constexpr std::array<Fixup,%d> Fixups{{'%len(fixups)]
for o,t in fixups:out.append('    {0x%x,0x%x},'%(o,t))
out+=['}};','struct Runtime {uint32_t begin,end,unwind;};','inline constexpr std::array<Runtime,%d> RuntimeFunctions{{'%len(runtime)]
for a,b,u in runtime:out.append('    {0x%x,0x%x,0x%x},'%(a,b,u))
out+=['}};','struct Unwind {uint32_t offset,size;std::array<uint8_t,64> bytes;};','inline constexpr std::array<Unwind,%d> UnwindBlocks{{'%len(unwind)]
for r,ch in unwind.items():out.append('    {0x%x,%d,{{%s}}},'%(offsets[r],len(ch),','.join('0x%02x'%v for v in ch)))
out+=['}};','}']
f = Path(sys.argv[2]) if len(sys.argv)>2 else Path(__file__).resolve().parents[1]/"d2rhud/plugin/States512Native.h"
f.write_text("\n".join(out)+"\n", encoding="utf-8")
print('Generated',f,'fixups',len(fixups),'runtime ranges',len(runtime),'unwind blocks',len(unwind))
