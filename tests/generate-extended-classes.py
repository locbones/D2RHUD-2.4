"""Regenerate the audited 1.2.69270 class patch descriptions (pefile/capstone)."""
import hashlib
import pathlib
import sys
import pefile
import capstone

path = pathlib.Path(sys.argv[1])
assert hashlib.sha256(path.read_bytes()).hexdigest() == '2c2ddb60a40ede3aaff51afb64e932621a03e32487687b6c64d88205fa652360'
pe = pefile.PE(str(path))
image = pe.get_memory_mapped_image()
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
# These are class bounds, not unit types, skill sentinels or unrelated sevens.
sites = [
    (0x1da7d0, 8, 'skill count vector length'),
    (0x1da7e8, 32, 'skill count vector shrink bytes'),
    (0x1da7fc, 8, 'skill count vector reserve'),
    (0x1da824, 32, 'skill count vector initialization bytes'),
    (0x1da831, 8, 'skill count vector size'),
    (0x1da868, 7, 'skill class counting pass'),
    (0x1da8c5, 8, 'skill index vector allocation multiplier'),
    (0x1da9bf, 7, 'skill class indexing pass'),
    (0x29bc1a, 7, 'initial class skill selection'),
    (0x292a40, 8, 'saved class skill count'),
    (0x292a52, 8, 'saved class skill index'),
    (0x292ab7, 8, 'saved class skill section length'),
    (0x319068, 8, 'class skill save writer'),
    (0x3195a0, 8, 'save helper player allocation'),
    (0x31a2bb, 8, 'new D2R character player allocation'),
    (0x31a721, 8, 'D2R save header expansion class validation'),
    (0x31aae3, 8, 'existing D2R character player allocation'),
    (0x31d930, 8, 'D2R saved class skill restore'),
    (0xc10f2, 8*40*4, 'animation residency flag initialization bytes'),
    (0x28fb59, 8, 'expansion character entry validation'),
    (0x28fde7, 8, 'initial server player allocation'),
    (0x2916b5, 8, 'player clone allocation'),
    (0x31059b, 8, 'saved player clone allocation'),
    (0x31b5a1, 8, 'corpse player allocation'),
    (0x2c42f3, 8, 'generic player allocation'),
    (0x209eab, 8, 'inventory class mapping length'),
    (0x460736, 8, 'frontend empty-model sentinel (Warlock now occupies 7)'),
    (0xc253c3, 8, 'frontend player widget default empty class'),
    (0xc04997, 8, 'empty selected-character preview'),
    (0xc04ee9, 8, 'empty character-list previews'),
    (0xc1dc2f, 8, 'empty alternate character preview'),
    (0xc3ddd1, 8, 'empty character preview reset'),
]
def hash_bytes(data):
    h = 14695981039346656037
    for b in data:
        h = ((h ^ b) * 1099511628211) & ((1 << 64) - 1)
    return h

rows = []
for rva, value, purpose in sites:
    ins = next(md.disasm(image[rva:rva+15], rva))
    old = bytes(ins.bytes)
    new = bytearray(old)
    width = 4 if rva in (0x1da7fc, 0x1da831, 0xc253c3, 0xc10f2) else 1
    new[-width:] = value.to_bytes(width, 'little')
    assert len(old) <= 12
    fmt = lambda data: '{' + ','.join('0x%02x' % b for b in data) + '}'
    rows.append('    {0x%x,%d,%s,%s}, // %s: %s %s' % (rva,len(old),fmt(old),fmt(new),purpose,ins.mnemonic,ins.op_str))

signatures = [(r-16, 48) for r,_,_ in sites] + [
    (0x59df70,0x3a9), (0x5aa750,0x14b), (0x5aa8a0,0x90), (0x5aa930,0xda),
    (0x42d0f0,0x134), (0x209e40,0xe0), (0x474a60,0xe0),
    (0xc049ad,7),(0xc1cdf9,7),(0xc3910b,7),(0xc3d731,7),
    (0x52320,0x3b0),(0xc2e740,0x285),(0xc2e9d0,0x1f0),
    (0x10a2ec,11),
    (0xbc4da4,12),(0xbc4e9d,11),(0xbc4f52,11),(0xbc5005,11),
    (0xc0e74,7),(0xc10eb,7),(0xc0ef8,0xac),
    (0x317bb7,7),(0x31d918,9),
]
out = '''// Generated by tests/generate-extended-classes.py; do not widen bounds globally.
#pragma once
#include <array>
#include <cstdint>
namespace ExtendedClasses::Data {
struct Patch { uint32_t rva; uint8_t size; std::array<uint8_t,12> before,after; };
inline constexpr std::array<Patch,%d> Patches{{
%s
}};
struct Signature { uint32_t rva,size; uint64_t hash; };
inline constexpr std::array<Signature,%d> Signatures{{
%s
}};
}
''' % (len(rows),'\n'.join(rows),len(signatures),'\n'.join('    {0x%x,0x%x,0x%016xULL},' % (r,n,hash_bytes(image[r:r+n])) for r,n in signatures))
target = pathlib.Path(__file__).parent.parent / 'd2rhud/plugin/ExtendedClassesData.h'
target.write_text(out)
print(target)
