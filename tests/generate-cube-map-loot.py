"""Audit the TC-selection wrapper and pointer-based drop ABI for extra picks.

Runtime relocates the wrapper and replaces its final call with a scoped private
TC-record adapter. The actual native TC walker is never rewritten or copied.
"""
from pathlib import Path
import hashlib
import struct
import sys
import capstone
import pefile

source = Path(sys.argv[1])
assert hashlib.sha256(source.read_bytes()).hexdigest().upper() in {
    "E4E13570E60C0A65CB0469D6659BE8A6008F9433AC50DB1C4F94501D7D9016F8",
    "2C2DDB60A40EDE3AAFF51AFB64E932621A03E32487687B6C64D88205FA652360",
}, "Unsupported executable"
pe = pefile.PE(str(source))
data = pe.get_memory_mapped_image()
begin, end = 0x2F9D50, 0x2F9EBB
call = 0x2F9EA1
assert data[call:call + 5] == bytes.fromhex("e86af3ffff")
assert data[0x2F92A7:0x2F92AB] == bytes.fromhex("418b410c")  # root Picks
assert data[0x2F939F:0x2F93A9] == bytes.fromhex("418b470c85c00f889702")
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
md.detail = True
fixups = []
for ins in md.disasm(data[begin:end], begin):
    if ins.disp_size == 4 and any(op.type == capstone.CS_OP_MEM and op.mem.base == capstone.x86.X86_REG_RIP for op in ins.operands):
        fixups.append((ins.address - begin + ins.disp_offset, ins.address + ins.size + ins.disp, ins.address + ins.size - begin))
    if (ins.group(capstone.CS_GRP_CALL) or ins.group(capstone.CS_GRP_JUMP)) and ins.operands and ins.operands[0].type == capstone.CS_OP_IMM:
        target = ins.operands[0].imm
        if not begin <= target < end:
            assert ins.imm_size == 4 and ins.imm_offset + 4 == ins.size
            fixups.append((ins.address - begin + ins.imm_offset, target, ins.address + ins.size - begin))

entry = next(e.struct for e in pe.DIRECTORY_ENTRY_EXCEPTION if e.struct.BeginAddress == begin)
assert entry.EndAddress == end
u = entry.UnwindData
assert data[u] >> 3 == 0
unwind = data[u:u + 4 + ((data[u + 2] + 1) & ~1) * 2]
out = [
    "// Generated by tests/generate-cube-map-loot.py; do not edit.",
    "#pragma once", "#include <array>", "#include <cstdint>",
    "namespace CubeMap::LootNativeData {",
    "inline constexpr uint32_t Source=0x2f9d50, Size=0x16b, Allocation=0x3000;",
    "inline constexpr uint32_t Walker=0x2f9210, WalkerCall=0x152, WalkerNext=0x156, Adapter=0x400;",
    "inline constexpr uint32_t RecordSize=0x140, Picks=0xc;",
    "struct Fixup {uint32_t offset,target,next;};",
    f"inline constexpr std::array<Fixup,{len(fixups)}> Fixups{{{{",
]
out.extend("    {0x%x,0x%x,0x%x}," % x for x in fixups)
out += ["}};", "struct Runtime {uint32_t begin,end,unwind;};", "inline constexpr std::array<Runtime,1> RuntimeFunctions{{{0,Size,0x2000}}};",
        "struct Unwind {uint32_t offset,size;std::array<uint8_t,64> bytes;};", "inline constexpr std::array<Unwind,1> UnwindBlocks{{",
        "    {0x2000,%d,{{%s}}}," % (len(unwind), ",".join("0x%02x" % v for v in unwind)), "}};"]
out += ["struct Signature {uint32_t rva,size;uint64_t hash;};", "inline constexpr std::array<Signature,2> Signatures{{"]
for r, e in ((begin, end), (0x2F9210, 0x2F9D42)):
    h = 14695981039346656037
    for value in data[r:e]:
        h = ((h ^ value) * 1099511628211) & ((1 << 64) - 1)
    out.append("    {0x%x,0x%x,0x%016xULL}," % (r, e - r, h))
out += ["}};", "}", '#include "CubeMapLootWalkerNative.h"']
destination = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "d2rhud/plugin/CubeMapLootNative.h"
destination.write_text("\n".join(out) + "\n", encoding="utf-8")
print("Generated", destination, "fixups", len(fixups), "unwind", len(unwind))
