"""Emit exact native function guards for per-level layout regeneration."""
from pathlib import Path
import hashlib
import struct
import sys
import pefile

source = Path(sys.argv[1])
assert hashlib.sha256(source.read_bytes()).hexdigest().upper() in {
    'E4E13570E60C0A65CB0469D6659BE8A6008F9433AC50DB1C4F94501D7D9016F8',
    '2C2DDB60A40EDE3AAFF51AFB64E932621A03E32487687B6C64D88205FA652360',
}
pe = pefile.PE(str(source))
image = pe.get_memory_mapped_image()
entries = {e.struct.BeginAddress: e.struct for e in pe.DIRECTORY_ENTRY_EXCEPTION}

def root(entry):
    r = entry.UnwindData
    if image[r] >> 3 & 4:
        n = 4 + ((image[r+2]+1) & ~1)*2
        return root(entries[struct.unpack_from('<I', image, r+n)[0]])
    return entry.BeginAddress

groups = {}
for e in entries.values():
    groups.setdefault(root(e), []).append(e)
addresses = [0x1e7860, 0x1e7f70, 0x1e8390, 0x1d0a20, 0x22e7f0, 0x2fa090, 0x231510,
             0x241fa0, 0x242b70, 0x242400, 0x2424d0, 0x6cd130, 0x2782b0, 0x158aa50]
lines = ['// Generated by tests/generate-cube-map-layout.py; do not edit.',
         '#pragma once', '#include <array>', '#include <cstdint>',
         'namespace CubeMap::LayoutNative {',
         'struct Signature {uint32_t rva,size;uint64_t hash;};',
         f'inline constexpr std::array<Signature,{len(addresses)}> Signatures{{{{']
for address in addresses:
    # Leaf status-list unlink/link routine has no unwind-table entry.
    end = {0x241fa0:0x242037, 0x158aa50:0x158ab40}.get(address)
    if end is None:
        end = max(e.EndAddress for e in groups[root(entries[address])])
    value = 14695981039346656037
    for byte in image[address:end]:
        value = ((value ^ byte) * 1099511628211) & ((1 << 64)-1)
    lines.append(f'    {{0x{address:x},0x{end-address:x},0x{value:016x}ULL}},')
lines += ['}};', '}']
destination = Path(sys.argv[2]) if len(sys.argv)>2 else Path(__file__).resolve().parents[1]/'d2rhud/plugin/CubeMapLayoutNative.h'
destination.write_text('\n'.join(lines)+'\n')
print('Generated', destination)
