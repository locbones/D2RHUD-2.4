"""Generate audited D2R 1.2.69270 map monster initialization relocation/unwind metadata.
No executable code is distributed: runtime copies the verified game routine.
Runtime copies select a run-specific level before native monster stat calculation.
The original GS exception handler, cookie offset and chained unwind data are retained.
"""
from pathlib import Path
import hashlib
import struct
import sys
import capstone
import pefile

source=Path(sys.argv[1])
assert hashlib.sha256(source.read_bytes()).hexdigest().upper()=="2C2DDB60A40EDE3AAFF51AFB64E932621A03E32487687B6C64D88205FA652360", "Unsupported executable"
pe=pefile.PE(str(source)); data=pe.get_memory_mapped_image()
md=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_64);md.detail=True
begin,end=0x33f380,0x3406e1
assert data[0x33f59b:0x33f5a4]==bytes.fromhex('450fbfbc46de000000')
assert data[0x33f60b:0x33f611]==bytes.fromhex('440fbf7c411a')
fixups=[];unwind={};runtime=[]
def uw(r):
    if r in unwind:return
    h=data[r:r+4];flags=h[0]>>3;n=4+((h[2]+1)&~1)*2
    assert flags in (0,3,4)
    chunk=bytearray(data[r:r+n+(12 if flags&4 else 8 if flags==3 else 0)]);unwind[r]=chunk
    if flags&4:uw(struct.unpack_from('<III',chunk,n)[2])
for ins in md.disasm(data[begin:end],begin):
    if ins.disp_size==4 and any(op.type==capstone.CS_OP_MEM and op.mem.base==capstone.x86.X86_REG_RIP for op in ins.operands):
        fixups.append((ins.address-begin+ins.disp_offset,ins.address+ins.size+ins.disp,ins.address+ins.size-begin))
    if ins.group(capstone.CS_GRP_CALL) or ins.group(capstone.CS_GRP_JUMP):
        if ins.operands and ins.operands[0].type==capstone.CS_OP_IMM:
            target=ins.operands[0].imm
            if not begin<=target<end:
                assert ins.imm_size==4 and ins.imm_offset+4==ins.size
                fixups.append((ins.address-begin+ins.imm_offset,target,ins.address+ins.size-begin))
for e in pe.DIRECTORY_ENTRY_EXCEPTION:
    x=e.struct
    if begin<=x.BeginAddress<end:
        assert x.EndAddress<=end
        runtime.append((x.BeginAddress-begin,x.EndAddress-begin,x.UnwindData));uw(x.UnwindData)
offsets={};nextoff=0x2000
for r,chunk in unwind.items():offsets[r]=nextoff;nextoff=(nextoff+len(chunk)+3)&~3
for chunk in unwind.values():
    if chunk[0]>>3==3:
        n=4+((chunk[2]+1)&~1)*2
        assert struct.unpack_from('<II',chunk,n)==(0x14359a4,0xd0)
        struct.pack_into('<I',chunk,n,0x2d00)
    if chunk[0]>>3&4:
        n=4+((chunk[2]+1)&~1)*2;x,y,u=struct.unpack_from('<III',chunk,n)
        assert begin<=x<y<=end
        struct.pack_into('<III',chunk,n,x-begin,y-begin,offsets[u])
out=['// Generated by tests/generate-cube-map-monsters.py; do not edit.', '#pragma once','#include <array>','#include <cstdint>', 'namespace CubeMap::MonsterNativeData {', 'inline constexpr uint32_t Source=0x33f380, Size=0x1361, Allocation=0x3000;', 'struct Fixup {uint32_t offset,target,next;};',f'inline constexpr std::array<Fixup,{len(fixups)}> Fixups{{{{']
out.extend('    {0x%x,0x%x,0x%x},'%x for x in fixups);out+=['}};', 'struct Runtime {uint32_t begin,end,unwind;};',f'inline constexpr std::array<Runtime,{len(runtime)}> RuntimeFunctions{{{{']
out.extend('    {0x%x,0x%x,0x%x},'%(a,b,offsets[u]) for a,b,u in runtime);out+=['}};','struct Unwind {uint32_t offset,size;std::array<uint8_t,64> bytes;};',f'inline constexpr std::array<Unwind,{len(unwind)}> UnwindBlocks{{{{']
out.extend('    {0x%x,%d,{{%s}}},'%(offsets[r],len(ch),','.join('0x%02x'%v for v in ch)) for r,ch in unwind.items());out+=['}};']
entries={e.struct.BeginAddress:e.struct for e in pe.DIRECTORY_ENTRY_EXCEPTION}
def root(e):
    r=e.UnwindData;h=data[r:r+4]
    if h[0]>>3&4:
        n=4+((h[2]+1)&~1)*2
        return root(entries[struct.unpack_from('<I',data,r+n)[0]])
    return e.BeginAddress
groups={}
for e in entries.values():groups.setdefault(root(e),[]).append(e)
addresses=[0x33f380,0x28b920,0x6c750,0x85060,0x413960,0x1e2e70,0x1e2e00,0x1e6260]
out+=['struct Signature {uint32_t rva,size;uint64_t hash;};',f'inline constexpr std::array<Signature,{len(addresses)}> Signatures{{{{']
for r in addresses:
    group=groups[root(entries[r])];e=max(x.EndAddress for x in group)
    h=14695981039346656037
    for value in data[r:e]:h=((h^value)*1099511628211)&((1<<64)-1)
    out.append('    {0x%x,0x%x,0x%016xULL},'%(r,e-r,h))
out+=['}};','}']
destination=Path(sys.argv[2]) if len(sys.argv)>2 else Path(__file__).resolve().parents[1]/'d2rhud/plugin/CubeMapMonsterNative.h'
destination.write_text('\n'.join(out)+'\n',encoding='utf-8')
print('Generated',destination,'fixups',len(fixups),'unwind blocks',len(unwind))

