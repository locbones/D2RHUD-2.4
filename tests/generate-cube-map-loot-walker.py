"""Relocation metadata for a private native TC walker with child-copy lookup.
Only the inline child TC lookup is redirected. Native pick traversal, RNG,
quality, quantity and item creation remain the audited game's own code.
"""
from pathlib import Path
import hashlib
import struct
import sys
import capstone
import pefile

source=Path(sys.argv[1])
assert hashlib.sha256(source.read_bytes()).hexdigest().upper() in {
    'E4E13570E60C0A65CB0469D6659BE8A6008F9433AC50DB1C4F94501D7D9016F8',
    '2C2DDB60A40EDE3AAFF51AFB64E932621A03E32487687B6C64D88205FA652360'}, 'Unsupported executable'
pe=pefile.PE(str(source));data=pe.get_memory_mapped_image()
begin,end=0x2f9210,0x2f9d42
lookup,lookupEnd=0x2f9717,0x2f973a
assert data[lookup:lookupEnd]==bytes.fromhex('664585ff741a4c3b3d945f9a0173114f8d0cbf49c1e1064c030d7b5f9a01eb034533c9')
md=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_64);md.detail=True
fixups=[];unwind={};runtime=[]
def uw(r):
    if r in unwind:return
    h=data[r:r+4];flags=h[0]>>3;n=4+((h[2]+1)&~1)*2
    assert flags in (0,3,4)
    chunk=bytearray(data[r:r+n+(12 if flags&4 else 8 if flags==3 else 0)]);unwind[r]=chunk
    if flags&4:uw(struct.unpack_from('<III',chunk,n)[2])
for ins in md.disasm(data[begin:end],begin):
    if ins.disp_size==4 and any(op.type==capstone.CS_OP_MEM and op.mem.base==capstone.x86.X86_REG_RIP for op in ins.operands):fixups.append((ins.address-begin+ins.disp_offset,ins.address+ins.size+ins.disp,ins.address+ins.size-begin))
    if (ins.group(capstone.CS_GRP_CALL) or ins.group(capstone.CS_GRP_JUMP)) and ins.operands and ins.operands[0].type==capstone.CS_OP_IMM:
        target=ins.operands[0].imm
        if not begin<=target<end:
            assert ins.imm_size==4 and ins.imm_offset+4==ins.size
            fixups.append((ins.address-begin+ins.imm_offset,target,ins.address+ins.size-begin))
for entry in pe.DIRECTORY_ENTRY_EXCEPTION:
    x=entry.struct
    if begin<=x.BeginAddress<end:
        assert x.EndAddress<=end
        runtime.append((x.BeginAddress-begin,x.EndAddress-begin,x.UnwindData));uw(x.UnwindData)
offsets={};nextoff=0x2000
for r,chunk in unwind.items():offsets[r]=nextoff;nextoff=(nextoff+len(chunk)+3)&~3
for chunk in unwind.values():
    n=4+((chunk[2]+1)&~1)*2
    if chunk[0]>>3==3:
        assert struct.unpack_from('<II',chunk,n)==(0x14359a4,0x690)
        struct.pack_into('<I',chunk,n,0x2d00)
    if chunk[0]>>3&4:
        x,y,u=struct.unpack_from('<III',chunk,n);assert begin<=x<y<=end
        struct.pack_into('<III',chunk,n,x-begin,y-begin,offsets[u])
# Adapter saves all volatile integer/XMM registers except r9 (the result).
# Its sole stack allocation has ordinary x64 unwind metadata.
adapter=bytearray(bytes.fromhex('4881ecb8000000'))
for code in ('4889442420','48894c2428','4889542430','4c89442438','4c89542440','4c895c2448'):adapter.extend(bytes.fromhex(code))
for reg in range(6):adapter.extend(bytes((0xf3,0x0f,0x7f,0x44+(reg<<3),0x24,0x50+reg*16)) if reg<3 else bytes((0xf3,0x0f,0x7f,0x84+(reg<<3),0x24))+struct.pack('<I',0x50+reg*16))
adapter.extend(bytes.fromhex('418bcf')) # ecx=r15d: selected child ID
callOffset=len(adapter);adapter.extend(bytes.fromhex('e800000000'))
adapter.extend(bytes.fromhex('4c8bc8')) # r9=rax
for reg in range(6):adapter.extend(bytes((0xf3,0x0f,0x6f,0x44+(reg<<3),0x24,0x50+reg*16)) if reg<3 else bytes((0xf3,0x0f,0x6f,0x84+(reg<<3),0x24))+struct.pack('<I',0x50+reg*16))
for code in ('488b442420','488b4c2428','488b542430','4c8b442438','4c8b542440','4c8b5c2448'):adapter.extend(bytes.fromhex(code))
adapter.extend(bytes.fromhex('4881c4b8000000c3'))
struct.pack_into('<i',adapter,callOffset+1,0x1a00-(0x1800+callOffset+5))
out=['// Generated by tests/generate-cube-map-loot-walker.py; do not edit.','#pragma once','#include <array>','#include <cstdint>','namespace CubeMap::LootWalkerNativeData {',
     'inline constexpr uint32_t Source=0x2f9210, Size=0xb32, Allocation=0x3000;',
     'inline constexpr uint32_t Lookup=0x507, LookupSize=0x23, Adapter=0x1800, LookupJump=0x1a00;',
     'struct Fixup {uint32_t offset,target,next;};',f'inline constexpr std::array<Fixup,{len(fixups)}> Fixups{{{{']
out.extend('    {0x%x,0x%x,0x%x},'%x for x in fixups);out+=['}};','struct Runtime {uint32_t begin,end,unwind;};',f'inline constexpr std::array<Runtime,{len(runtime)+1}> RuntimeFunctions{{{{']
out.extend('    {0x%x,0x%x,0x%x},'%(a,b,offsets[u]) for a,b,u in runtime);out+=['    {0x1800,0x%x,0x2400},'%(0x1800+len(adapter)),'}};','struct Unwind {uint32_t offset,size;std::array<uint8_t,64> bytes;};',f'inline constexpr std::array<Unwind,{len(unwind)+1}> UnwindBlocks{{{{']
out.extend('    {0x%x,%d,{{%s}}},'%(offsets[r],len(ch),','.join('0x%02x'%v for v in ch)) for r,ch in unwind.items());out+=['    {0x2400,8,{{0x01,0x07,0x02,0x00,0x07,0x01,0x17,0x00}}},','}};',f'inline constexpr std::array<uint8_t,{len(adapter)}> AdapterBytes{{{{'+','.join('0x%02x'%v for v in adapter)+'}};','}']
destination=Path(sys.argv[2]) if len(sys.argv)>2 else Path(__file__).resolve().parents[1]/'d2rhud/plugin/CubeMapLootWalkerNative.h'
destination.write_text('\n'.join(out)+'\n',encoding='utf-8')
print('Generated',destination,'fixups',len(fixups),'adapter bytes',len(adapter))
