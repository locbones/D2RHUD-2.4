"""Export RMD-MP's description-only Codex identities without executing Lua."""
import argparse
import hashlib
import json
from pathlib import Path
import re


def reference(text, catalog):
    rows = []
    families = {}
    blocks = list(re.finditer(r'\{\s*--Testament ([1-7]):([1-7]|Complete) Description\s*\n', text))
    for match in blocks:
        end = text.find('{ --', match.end())
        block = text[match.end():end if end >= 0 else len(text)]
        code = re.search(r'\bcode\s*=\s*"([A-Za-z0-9]{3})"', block)
        english = re.search(r'\benUS\s*=\s*("(?:\\.|[^"\\])*")', block)
        if not code or not english:
            raise ValueError('Incomplete Testament description')
        group, part = int(match[1]), match[2]
        code = code[1]
        if part != 'Complete':
            label = re.sub(r'\{[^}]+\}', '', json.loads(english[1])).strip().split('\n')[0].lstrip('- ')
            if label != f'Testament {group}:{part}':
                raise ValueError('Testament header and visible description disagree')
            base = catalog['bases'][code]
            family = base.get('original_name', base['name'])
            family = family.split(' - Testament ', 1)[0]
            if not family.startswith('Codex of '):
                raise ValueError('Unexpected Codex family name: ' + family)
            if group in families and families[group] != family:
                raise ValueError('Inconsistent Codex family')
            families[group] = family
            name, quality = family + ' - ' + label, 2
        else:
            named = [r for r in catalog['unique'].values() if r['code'] == code]
            if len(named) != 1:
                raise ValueError('Completed Testament must have one unique identity')
            original = named[0].get('original_name', named[0]['name']).split(' - Complete Codex ', 1)[0]
            name, quality = original + f' - Complete Codex {group}', 7
        rows.append({'code': code, 'quality': quality, 'group': group, 'part': part, 'name': name})
    if len(rows) != 56 or len({r['code'] for r in rows}) != 56:
        raise ValueError('Expected 49 Codex pieces and seven completed Testaments')
    for group in range(1, 8):
        if {r['part'] for r in rows if r['group'] == group} != set(map(str, range(1, 8))) | {'Complete'}:
            raise ValueError('Incomplete Codex reference')
    return {'schema': 1, 'mod': 'RMD-MP', 'source': 'Pandemonium/Filters/override_rules.lua',
            'source_sha256': hashlib.sha256(text.encode('utf-8')).hexdigest(), 'items': rows}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('rules', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    catalog_path = root / 'tools/marketplace/server/public/assets/catalog.json'
    catalog = json.loads(catalog_path.read_text(encoding='utf-8'))
    data = reference(args.rules.read_text(encoding='utf-8-sig'), catalog)
    (root / 'tools/marketplace/assets/rmd-codex.json').write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')
    lines = ['#pragma once', '#include <array>', '#include <string>', '#include <string_view>',
             '// Generated by tools/marketplace/build-codex-reference.py; identities stay unchanged.',
             'namespace Marketplace {', 'struct CodexReference {std::string_view code;int quality;std::string_view name;};',
             'inline constexpr std::array<CodexReference,56> CodexReferences{{']
    lines += ['    {' + json.dumps(r['code']) + ',' + str(r['quality']) + ',' + json.dumps(r['name']) + '},' for r in data['items']]
    lines += ['}};', 'inline std::string CodexName(std::string_view mod,std::string_view code,int quality,std::string_view fallback){',
              '    if(mod=="RMD-MP")for(const auto& r:CodexReferences)if(r.code==code&&r.quality==quality)return std::string(r.name);',
              '    return std::string(fallback);', '}', '}']
    (root / 'd2rhud/plugin/MarketplaceCodexNames.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Exported 49 exact Codex pieces and seven completed Testaments from the override descriptions.')


if __name__ == '__main__':
    main()
